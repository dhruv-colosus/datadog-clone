const NOW = Date.now();

function makeSeries(
  service: string,
  baseHits: number,
  errorRate = 0,
  baseLatency = 50,
): ApmServiceSeries {
  const points = Array.from({ length: 24 }, (_, i) => {
    const t = NOW - (24 - i) * 150_000;
    const factor = 0.5 + 0.5 * Math.sin((i + service.length) * 0.6);
    const hits = Math.max(0, Math.round(baseHits * factor * (i > 19 ? 2.4 : 0.05)));
    return {
      t,
      hits,
      errors: Math.round(hits * errorRate),
      latencyMs: baseLatency + Math.round(40 * factor),
    };
  });
  return { service, points };
}

export function getServiceSummarySeries(serviceId: string): ApmServiceSeries[] {
  const svc = APM_SERVICES.find((s) => s.id === serviceId);
  if (!svc) return [];
  const baseHits = svc.totalRequests;
  return [
    makeSeries(serviceId, baseHits, svc.errorRate ?? 0, svc.p95LatencyMs / 4),
  ];
}

export function getServiceResourceSeries(serviceId: string): ApmServiceSeries[] {
  const resources = getResourcesForService(serviceId).slice(0, 5);
  return resources.map((r, i) =>
    makeSeries(r.id, r.requests ?? 4, r.errorRate, r.p95LatencyMs / 6 + i * 4),
  );
}

