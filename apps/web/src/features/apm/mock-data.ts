export const APM_SPANS: ApmSpan[] = (() => {
  const spans: ApmSpan[] = [];
  let id = 0;
  const baseTime = NOW - 60_000;
  for (let cycle = 0; cycle < 13; cycle += 1) {
    SAMPLE_SPAN_TEMPLATES.forEach((tpl, i) => {
      id += 1;
      spans.push({
        id: `span_${id}`,
        timestampMs: baseTime + cycle * 8_000 + i * 60,
        ...tpl,
      });
    });
  }
  return spans.sort((a, b) => b.timestampMs - a.timestampMs);
})();
